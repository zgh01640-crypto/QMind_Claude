def markdown(page_no, raw_rows):
    lines = [
        "# 附录 A 材料、机械台班参考价格表",
        "",
        f"## 续表 A（PDF 第{page_no}页）",
        "",
        "| 序号 | 名称 | 单位 | 价格（元） |",
        "|---:|---|:---:|---:|",
    ]
    for raw in raw_rows.strip().splitlines():
        number, name, unit, price = raw.split("|")
        lines.append(f"| {number} | {name} | {unit} | {price} |")
    return "\n".join(lines) + "\n"


